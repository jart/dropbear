// Generates symbol/stocks.go from the Alpaca assets API.
//
// Usage:
//
//	go run symbol/gen/main.go
package main

import (
	"dropbear/broker/alpaca"
	"fmt"
	"os"
	"slices"
	"strings"
)

func main() {
	client := alpaca.NewClient()
	if err := client.SyncAssets(); err != nil {
		fmt.Fprintf(os.Stderr, "error fetching assets: %v\n", err)
		os.Exit(1)
	}

	// extra symbols not in Alpaca's equity assets (indices, options underlyings)
	extras := []string{"NDX", "SPXW", "SPEQX", "RUTW", "VIX", "VIXW", "XSP"}

	// collect decent symbols
	type entry struct {
		name   string
		symbol string
	}
	var entries []entry
	alpaca.Lock.RLock()
	for _, asset := range alpaca.Assets {
		if !asset.IsDecent() {
			continue
		}
		name := asset.Symbol.String()
		if len(name) > 5 {
			continue // skip long symbols
		}
		if strings.ContainsAny(name, "./-") {
			continue // skip symbols with invalid Go identifier chars
		}
		entries = append(entries, entry{name: name})
	}
	alpaca.Lock.RUnlock()

	// add extras (dedup)
	seen := make(map[string]bool)
	for _, e := range entries {
		seen[e.name] = true
	}
	for _, name := range extras {
		if !seen[name] {
			entries = append(entries, entry{name: name})
		}
	}

	// sort alphabetically
	slices.SortFunc(entries, func(a, b entry) int {
		return strings.Compare(a.name, b.name)
	})

	// compute alignment
	maxLen := 0
	for _, e := range entries {
		if len(e.name) > maxLen {
			maxLen = len(e.name)
		}
	}

	// generate Go source
	var buf strings.Builder
	buf.WriteString("// Code generated by go run symbol/gen/main.go; DO NOT EDIT.\n\n")
	buf.WriteString("package symbol\n\n")
	buf.WriteString("const (\n")
	for _, e := range entries {
		padding := strings.Repeat(" ", maxLen-len(e.name))
		parts := make([]string, len(e.name))
		for i, c := range e.name {
			if i == 0 {
				parts[i] = fmt.Sprintf("'%c'", c)
			} else {
				parts[i] = fmt.Sprintf("'%c'<<%d", c, i*8)
			}
		}
		fmt.Fprintf(&buf, "\t%s %s= Symbol(%s)\n", e.name, padding, strings.Join(parts, " | "))
	}
	buf.WriteString(")\n")

	if err := os.WriteFile("symbol/stocks.go", []byte(buf.String()), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "error writing symbol/stocks.go: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("wrote %d symbols to symbol/stocks.go\n", len(entries))
}
